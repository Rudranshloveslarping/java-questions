public class PrimitiveDataTypes {
    public static void main(String[] args) {
        byte a = 10;
        short b = 200;
        int c = 3000;
        long d = 40000L;
        float e = 5.5f;
        double f = 12.345;
        char g = 'A';
        boolean h = true;
        System.out.println(a + " " + b + " " + c + " " + d + " " + e + " " + f + " " + g + " " + h);
    }
}
